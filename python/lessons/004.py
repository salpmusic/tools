# Python入門 第4回
# 四則演算と計算結果の表示
# Python 3.7対応

print("=== 第4回：四則演算 ===")

# 1. 基本の四則演算
print("\n【1】基本の計算")
print("7 + 2 =", 7 + 2)
print("7 - 2 =", 7 - 2)
print("7 * 2 =", 7 * 2)
print("7 / 2 =", 7 / 2)

# 2. 割り算の違い
# BASICの \ に近いのが //
print("\n【2】割り算の違い")
print("7 / 2 =", 7 / 2)
print("7 // 2 =", 7 // 2)
print("-7 // 2 =", -7 // 2)

# 3. 余りとべき乗
# BASIC: MOD -> Python: %
# BASIC: ^   -> Python: **
print("\n【3】余りとべき乗")
print("10 % 3 =", 10 % 3)
print("2 ** 3 =", 2 ** 3)

# 4. 計算の順番
print("\n【4】計算の順番")
print("2 + 3 * 4 =", 2 + 3 * 4)
print("(2 + 3) * 4 =", (2 + 3) * 4)
print("2 ** 3 ** 2 =", 2 ** 3 ** 2)

# 5. 小数の誤差
print("\n【5】小数の誤差")
print("0.1 + 0.2 =", 0.1 + 0.2)
print("roundの結果 =", round(0.1 + 0.2, 2))

# 6. 結果を見やすく表示
print("\n【6】printとf-string")
a = 10
b = 3

print("普通の割り算:", a / b)
print(f"{a} ÷ {b} = {a / b:.2f}")
print(f"整数の商 = {a // b}")
print(f"余り = {a % b}")

# 7. 練習問題の答え合わせ
print("\n【7】練習問題")

print("問題1")
print("17 // 5 =", 17 // 5)
print("17 % 5 =", 17 % 5)
print("3 ** 2 =", 3 ** 2)

print("問題2")
print("10 + 6 / 2 =", 10 + 6 / 2)
print("(10 + 6) / 2 =", (10 + 6) / 2)

print("\n第4回はここまで！")
