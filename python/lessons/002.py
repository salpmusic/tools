# 第2回：変数と計算 の例
# Python 3.7 対応

print("=== 変数の基本 ===")
a = 10
b = 20
print(a + b)

print("\n=== 計算の例 ===")
x = 7
y = 3
print(x + y)
print(x * y)
print(x ** 2)

print("\n=== 結果を変数に入れる ===")
total = a + b
print(total)

print("\n=== 練習問題1 ===")
price = 1200
tax = 1.1
print(price * tax)

print("\n=== 練習問題2 ===")
num = 17
print(num // 2)
print(num % 2)

print("\n=== 大文字小文字の違い（参考） ===")
score = 80
Score = 90
print(score) # 80
print(Score) # 90
